"""
Pydantic v2 domain models for SQLPilot.
Strict typing for schema introspection, query generation, execution results, and self-healing telemetry.
"""

from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field


class ColumnInfo(BaseModel):
    """Metadata describing a single table column."""
    name: str = Field(..., description="Column name")
    data_type: str = Field(..., description="SQL data type (e.g. INTEGER, TEXT, REAL)")
    is_primary_key: bool = Field(default=False, description="Whether this column is part of the primary key")
    nullable: bool = Field(default=True, description="Whether NULL values are allowed")


class TableSchema(BaseModel):
    """Metadata and sample preview describing a relational table."""
    table_name: str = Field(..., description="Name of the table")
    columns: List[ColumnInfo] = Field(default_factory=list, description="List of columns")
    foreign_keys: List[Dict[str, str]] = Field(
        default_factory=list,
        description="Foreign key relationships (e.g. {'from': 'customer_id', 'to_table': 'customers', 'to_column': 'id'})"
    )
    sample_rows: List[Dict[str, Any]] = Field(
        default_factory=list,
        description="Few sample rows to assist LLM with value formats"
    )


class DatabaseMetadata(BaseModel):
    """Complete schema definition for all tables in the connected database."""
    dialect: str = Field(default="sqlite", description="SQL dialect (sqlite, postgresql, mysql)")
    tables: List[TableSchema] = Field(default_factory=list, description="All introspected tables")


class SQLGeneration(BaseModel):
    """The raw SQL query and reasoning generated by the LLM."""
    sql_query: str = Field(..., description="The executable SQL query")
    thought: str = Field(..., description="Step-by-step reasoning explaining table joins and filters")
    assumptions: List[str] = Field(
        default_factory=list,
        description="Assumptions made about ambiguous business terms (e.g. 'Active customer defined as status=active')"
    )


class QueryResult(BaseModel):
    """The tabular result set returned from safe database execution."""
    columns: List[str] = Field(..., description="Column names returned in the SELECT statement")
    rows: List[List[Any]] = Field(default_factory=list, description="Row tuples returned from execution")
    row_count: int = Field(..., ge=0, description="Total number of returned rows")
    execution_time_ms: float = Field(..., ge=0.0, description="Database query execution time in ms")


class QueryRepairAttempt(BaseModel):
    """Telemetry capturing a self-healing iteration when SQL fails."""
    attempt_number: int = Field(..., ge=1, description="Iteration number (1, 2, ...)")
    failed_sql: str = Field(..., description="The query that triggered a database error")
    error_message: str = Field(..., description="Exact database error traceback returned")
    repaired_sql: str = Field(..., description="The revised query generated by the model")
    fix_explanation: str = Field(..., description="What was corrected (e.g. 'Replaced invalid column with customer_id')")


class SQLPilotResponse(BaseModel):
    """The complete executive response returned to the user."""
    user_query: str = Field(..., description="Original question in plain English")
    final_sql: str = Field(..., description="The final valid SQL query executed")
    result: Optional[QueryResult] = Field(default=None, description="Query tabular results")
    business_summary: str = Field(..., description="Natural language executive explanation of the data")
    assumptions_made: List[str] = Field(default_factory=list, description="Explicit assumptions stated by the model")
    repairs: List[QueryRepairAttempt] = Field(
        default_factory=list,
        description="Self-healing repair logs if syntax/column errors occurred"
    )
    is_blocked_by_guardrail: bool = Field(default=False, description="True if query violated read-only safety rules")
    guardrail_reason: Optional[str] = Field(default=None, description="Explanation if query was blocked by firewall")
    total_latency_ms: float = Field(..., ge=0.0, description="Total round-trip latency in milliseconds")
